// RFC 4122 v4 from k6's crypto random bytes. Inlined rather than imported from
// jslib.k6.io so the test runs where outbound internet is blocked, which is
// the norm inside a bank.
import crypto from 'k6/crypto';

export function uuidv4() {
  const b = new Uint8Array(crypto.randomBytes(16));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
